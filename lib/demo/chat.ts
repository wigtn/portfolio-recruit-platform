/**
 * 답변 끝에 실려 오는 후속 질문의 표식.
 *
 * 모델이 `[[NEXT]]질문1|질문2` 한 줄을 답변 뒤에 붙인다. 칩을 따로 물으면
 * 왕복이 하나 더 늘어서, 이미 도는 답변 콜의 꼬리에 얹었다.
 */
export const NEXT_MARK = "[[NEXT]]";

/**
 * 답변에서 후속 질문을 떼어낸다.
 *
 * 스트리밍 중에도 불린다. 그래서 **마커가 도착하는 중인 상태**를 봐야
 * 한다 — "[[N"까지만 온 순간에 그대로 그리면 방문자가 대괄호 부스러기를
 * 본다. 꼬리가 마커의 앞부분이면 미리 감춘다.
 */
export function splitFollowups(text: string): {
  body: string;
  chips: string[];
} {
  const at = text.indexOf(NEXT_MARK);
  if (at < 0) {
    for (let n = NEXT_MARK.length - 1; n > 0; n -= 1) {
      if (text.endsWith(NEXT_MARK.slice(0, n))) {
        return { body: text.slice(0, text.length - n), chips: [] };
      }
    }
    return { body: text, chips: [] };
  }
  const chips = text
    .slice(at + NEXT_MARK.length)
    .split("|")
    .map((one) => one.trim())
    /* 줄바꿈 뒤에 딴 말을 붙이는 경우가 있다. 첫 줄만 질문으로 본다 */
    .map((one) => one.split("\n")[0].trim())
    .filter((one) => one.length > 1 && one.length <= 40)
    .slice(0, 2);
  return { body: text.slice(0, at).trimEnd(), chips };
}

/**
 * 지금 대화에 이어 붙일 칩을 고른다.
 *
 * 마지막으로 걸린 인텐트의 이웃을 먼저 세우고, 모자라면 기본 순서로
 * 채운다. 이미 물어본 것은 뺀다 — 같은 질문이 다시 제안되면 대화가
 * 제자리를 돈다.
 */
export function nextChips(
  lastIntentId: string | null,
  asked: Set<string>,
  limit = 4,
): ChatIntent[] {
  const picked: ChatIntent[] = [];
  const take = (id: string) => {
    if (picked.length >= limit) return;
    const intent = intentById(id);
    if (!intent?.chip) return;
    if (asked.has(intent.chip)) return;
    if (picked.some((p) => p.id === intent.id)) return;
    picked.push(intent);
  };

  for (const id of (lastIntentId && NEXT_BY_INTENT[lastIntentId]) ?? []) {
    take(id);
  }
  // 이웃만으로 모자라면 기본 순서로 채운다. 칩 줄이 비면 진입로가 사라진다
  for (const intent of INTENTS) take(intent.id);
  return picked;
}

/** 스크립트 답변. 키워드 점수로 고른다. 못 고르면 null(모른다고 말한다) */
export function intentById(id: string) {
  return INTENTS.find((intent) => intent.id === id) ?? null;
}

export function resolveScripted(text: string): ChatIntent | null {
  const q = text.toLowerCase().replace(/\s+/g, "");
  let best: { intent: ChatIntent; score: number } | null = null;

  for (const intent of INTENTS) {
    let score = 0;
    for (const word of intent.keywords) {
      if (q.includes(word.toLowerCase())) score += word.length;
    }
    if (score > 0 && (!best || score > best.score)) best = { intent, score };
  }

  return best?.intent ?? null;
}

/**
 * 화면 조작을 요청하는 신호.
 *
 * 이 말들이 하나라도 있으면 방문자는 무언가 열고, 짚고, 바꾸고, 쓰기를 바란다.
 * 그러면 도구 판단 콜을 반드시 태운다. 목록을 넉넉하게 잡는 이유는 비대칭
 * 때문이다. 여기서 조작 신호를 놓치면 "커뮤니티 보여줘"가 도구 없이 말로만
 * 답해지고, 데모의 간판 기능이 조용히 사라진다. 반대로 순수 질문을 조작으로
 * 잘못 봐도 손해는 도구 판단 콜 한 번(기존 그대로)뿐이다. 그래서 의심스러우면
 * 조작으로 친다.
 *
 * resolveScripted의 키워드 매칭과는 목적이 다르다. 저건 "무엇에 대한 질문인가"를
 * 고르고, 이건 "말로 답할까 화면을 건드릴까"를 가른다. "관리자 화면 보여줘"는
 * cms 인텐트에 매칭되지만 여기서는 조작이다("보여").
 */
const SCREEN_ACTION =
  /(보여|열어|열기|띄워|띄우|이동|데려가|가\s?줘|가\s?봐|짚어|눌러|누르|클릭|바꿔|바꾸|변경|전환|써\s?줘|작성|글\s?쓰|글\s?써|등록|올려|답변|답글|달아|반응|도움돼|스크랩|검색|찾아|팔로우|지원|인증|강조|하이라이트|테마|브랜드|색|초기화|리셋|안내|어디|관리자로|운영자로|회원으로|게스트로|백오피스|화면)/;

/**
 * 도구 없이 말로만 답해도 되는 순수 질문인가.
 *
 * 두 조건을 모두 넘어야 순수 질문이다. (1) 화면 조작 신호가 하나도 없고,
 * (2) 진행 중인 조작(trace)이 없다. 조작 중이면 다음 걸음이 남아 있을 수
 * 있으니 판단을 건너뛰지 않는다.
 *
 * 순수 질문이면 도구 판단 콜(한 번)을 아끼고 곧바로 답변 콜로 간다. 데모에서
 * 대부분의 첫 질문("유지보수는요?", "기간 얼마나 걸려요?")이 여기 해당해서
 * 턴당 OpenAI 호출이 둘에서 하나로 준다.
 */
export function isPureQuestion(text: string, midOperation: boolean): boolean {
  if (midOperation) return false;
  return !SCREEN_ACTION.test(text);
}

