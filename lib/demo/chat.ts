/**
 * 자동 재생 순서. 열면 이 대화가 스스로 흘러간다.
 *
 * 방문자에게 타이핑을 요구하면 대부분 그냥 닫는다. 무엇을 물어야 할지 모르기 때문이다.
 * 그래서 팔아야 할 순서대로 저희가 먼저 묻고 답한다:
 * 무엇을 만들 수 있나 → 얼마나 걸리나 → 인수 후 어떻게 되나 → 그래서 다음 단계.
 * 금액은 재생에서 뺐다. 요구사항 없이 던진 숫자는 상담 자리에서 뒤집힌다.
 *
 * 실호출(LLM)은 타지 않는다. 자동 재생은 매번 같아야 데모로 쓸 수 있고,
 * 열기만 해도 토큰이 나가면 비용 방어가 무너진다.
 */
